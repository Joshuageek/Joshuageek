    <!-- JavaScript for Questionnaire Form -->
    <script>
      let currentStep = 1;
      const totalSteps = 7;

      function updateProgressBar() {
        const progressPercent = (currentStep / totalSteps) * 100;
        document.getElementById('progress-bar-fill').style.width = progressPercent + '%';
      }

      function showStep(step) {
        document.querySelectorAll('.step-content').forEach(content => {
          content.style.display = 'none';
        });
        document.getElementById(`step-${step}`).style.display = 'block';
      }

      function goNext() {
        if (currentStep < totalSteps) {
          currentStep++;
          showStep(currentStep);
          updateProgressBar();
        }
        if (currentStep === totalSteps) {
          document.getElementById('nextButton').style.display = 'none';
          document.getElementById('submitButton').style.display = 'block';
        }
        document.getElementById('backButton').style.display = 'block';
      }

      function goBack() {
        if (currentStep > 1) {
          currentStep--;
          showStep(currentStep);
          updateProgressBar();
        }
        if (currentStep === 1) {
          document.getElementById('backButton').style.display = 'none';
        }
        document.getElementById('nextButton').style.display = 'block';
        document.getElementById('submitButton').style.display = 'none';
      }

      function handleFormSubmit(event) {
        event.preventDefault();
        alert("Thank you for completing the questionnaire!");
        // You can add code here to submit the form data to your server
      }

      document.getElementById('questionnaire').addEventListener('submit', handleFormSubmit);

      // Show the first step initially
      showStep(currentStep);
      updateProgressBar();

      // Handle "Attended Therapy" radio button change
      document.querySelectorAll('input[name="attendedTherapy"]').forEach(radio => {
        radio.addEventListener('change', function() {
          if (this.value !== 'No') {
            document.getElementById('previousTherapies').style.display = 'block';
          } else {
            document.getElementById('previousTherapies').style.display = 'none';
          }
        });
      });

      // Handle "Health Conditions" and "Triggers" select change
      document.getElementById('healthConditions').addEventListener('change', function() {
        if (this.value === 'Yes') {
          document.getElementById('healthConditionsDetail').style.display = 'block';
        } else {
          document.getElementById('healthConditionsDetail').style.display = 'none';
        }
      });

      document.getElementById('triggers').addEventListener('change', function() {
        if (this.value === 'Yes') {
          document.getElementById('triggersDetail').style.display = 'block';
        } else {
          document.getElementById('triggersDetail').style.display = 'none';
        }
      });
    </script>

